// Generates the raw FFI bindings in lib/src/ffi/ from the vendored BrainFlow
// headers. Run: dart run tool/ffigen.dart
//
// Needs libclang (on Debian/Ubuntu: `apt install libclang-dev`, or set
// LIBCLANG_PATH if it is not found automatically).
import 'dart:io';

import 'package:ffigen/ffigen.dart';

final _root = Platform.script.resolve('../');
final _include = _root.resolve('third_party/brainflow/include/');

/// Functions we never bind (platform glue not needed from Dart).
const _excluded = {'java_set_jnienv'};

Future<void> main() async {
  await _generate(
    headers: ['board_controller.h', 'board_info_getter.h'],
    asset: 'board_controller',
  );
  await _generate(headers: ['data_handler.h'], asset: 'data_handler');
  await _generate(headers: ['ml_module.h'], asset: 'ml_module');
}

Future<void> _generate({
  required List<String> headers,
  required String asset,
}) async {
  final entryPoints = [for (final h in headers) _include.resolve(h)];
  await FfiGenerator(
    input: Input(
      entryPoints: entryPoints,
      include: (header) => entryPoints.contains(header),
    ),
    output: Output(
      dart: DartOutput(path: _root.resolve('lib/src/ffi/$asset.g.dart')),
      style: NativeExternalBindings(
        assetId: 'package:flutter_brainflow/$asset',
      ),
      preamble: '''
// Generated by tool/ffigen.dart from third_party/brainflow/include.
// Do not edit by hand.
// ignore_for_file: type=lint
''',
    ),
    visitors: [
      Visitor(
        func: (node) =>
            node.isIncluded = !_excluded.contains(node.originalName),
      ),
    ],
  ).generate();
}
